// Writes src/platform/reportIndex.js: each converted report's summary row (Kavin's store.summary_row), so the
// seed and the list pages know every report without fetching its document. The viewer fetches the full
// report.json when a report is opened.
//
// node index.mjs --reports ../../public/portal/reports --out ../../src/platform/reportIndex.js
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const arg = k => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const dir = arg("--reports"), out = arg("--out");
if (!dir || !out) { console.error("usage: node index.mjs --reports <reports folder> --out <reportIndex.js>"); process.exit(1); }

// Underbody is not a section of Lemon Squad's checklist: a flagged finding is underbody when its item is the frame,
// rust, the muffler or the exhaust, or its note places it under the car (docs/platform/decisions.md)
const underbody = k => /Underbody|Frame|^Rust$|Muffler|Exhaust|Floors|Rockers/i.test(k.item) || /\b(underside|underbody|undercarriage|under the vehicle|underneath)\b/i.test(k.note || "");
const firstSentence = t => (t.match(/^.*?[.!?](?=\s|$)/) || [t])[0].trim();
const rows = readdirSync(dir).filter(id => /^\d{8}-\d{6}-[0-9a-f]{6}$/.test(id)).sort().map(id => {
  const d = JSON.parse(readFileSync(join(dir, id, "report.json"), "utf8"));
  return {id: d.id, filename: d.filename, vehicle: d.vehicle, vehicle_in_pdf: d.vehicle_in_pdf ?? null, inspection: d.inspection,
          summary: d.summary, pages: d.pages, image_count: d.images.length, photo_count: d.photo_count ?? d.images.length, size: d.size,
          // Inspectd AI's flags and issue counts, for the workspace overview (insight.py)
          ...(d.insight ? {insight_overview: {flags: Object.fromEntries(Object.entries(d.insight.flags).map(([k, f]) => [k, f.value])),
                                     surface_rust: !!d.insight.details?.surface_rust?.value,
                                     key_issues: {fail: d.insight.key_issues.filter(k => k.status === "fail").length,
                                                  attention: d.insight.key_issues.filter(k => k.status === "attention").length},
                                     summary: !!d.insight.summary,
                                     // for the Inspectd AI overview: every key issue as [section, item, status, consumable,
                                     // underbody], and the summary's first sentence for the vehicle list
                                     issues: d.insight.key_issues.map(k => [k.section, k.item, k.status, k.consumable, underbody(k)]),
                                     first_sentence: firstSentence(d.insight.summary?.text || "")}} : {})};
});
writeFileSync(out, `// Generated by tools/report-conversion/index.mjs from public/portal/reports/*/report.json. Do not edit by hand.
// Each report's summary row (inspection-dashboard reports_service store.summary_row); the full document,
// with its findings and photos, is fetched from public/portal/reports/<id>/report.json when it is opened.
export const REPORT_INDEX = ${JSON.stringify(Object.fromEntries(rows.map(r => [r.id, r])), null, 1)};
`);
console.log(`${rows.length} reports indexed into ${out}`);
